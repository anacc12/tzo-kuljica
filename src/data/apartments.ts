// Private accommodation listings
// Images live in /public/iznajmljivači/[slug]/  (any filenames, sorted alphabetically)
// Fields NOT shown publicly: e-visitor status, web stranica, sastanak, internal notes

export interface Apartment {
  slug: string
  name: string
  addressProperty: string    // Kukljica property address
  phones?: string[]          // all numbers (landline + mobile)
  email?: string
  types?: string             // e.g. "A4, AS4 x2, A2+1" — shown as-is
  featured?: boolean         // shown in homepage carousel
  description?: {
    hr: string
    en: string
  }
  images: string[]           // filenames inside /public/iznajmljivači/[slug]/
}

export type FilterCategory = 'all' | 'studio' | 'a2' | 'a4' | 'a5plus' | 'kuca'

export const FILTER_LABELS: Record<FilterCategory, { hr: string; en: string }> = {
  all:    { hr: 'Sve',    en: 'All'    },
  studio: { hr: 'Studio', en: 'Studio' },
  a2:     { hr: 'A2–A3', en: 'A2–A3'  },
  a4:     { hr: 'A4',    en: 'A4'     },
  a5plus: { hr: 'A5+',   en: 'A5+'    },
  kuca:   { hr: 'Kuća',  en: 'House'  },
}

export function getCategories(types: string | undefined): FilterCategory[] {
  if (!types) return ['all']
  const cats = new Set<FilterCategory>(['all'])
  for (const raw of types.split(',')) {
    const code = raw.trim().replace(/\s*x\d+$/, '').trim()
    if (/^AS/.test(code) || /^S\d/.test(code))  cats.add('studio')
    else if (/^A[23]/.test(code))  cats.add('a2')
    else if (/^A4/.test(code))     cats.add('a4')
    else if (/^A[5-9]/.test(code)) cats.add('a5plus')
    else if (/^KO/.test(code))     cats.add('kuca')
  }
  return Array.from(cats)
}

